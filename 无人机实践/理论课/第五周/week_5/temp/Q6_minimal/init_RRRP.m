%% RRRP Manipulator Initialization Parameters
% =========================================================================
% 文件功能：
%   本脚本用于初始化 RRRP 四自由度开链机械手的仿真参数。
%
% RRRP 结构：R1 - R2 - R3 - P4
%   R1、R2、R3：转动关节（Revolute Joint）
%   P4：移动关节（Prismatic Joint）
%
% 本脚本统一定义：
%   1. 连杆几何参数
%   2. 连杆质量与密度
%   3. 初始关节位形
%   4. 目标关节位形
%   5. 轨迹规划时间参数
%   6. PID/PD 控制参数
%   7. 仿真总时间
%
% 使用方法：
%   1.运行 Simulink 模型前，先在 MATLAB Command Window 中执行：
%       init_RRRP
%     或直接运行init_RRRP.m文件 
%   注：可在init_RRRP.m 文件中的8. PID gains部分修改每个关节的PID参数，在9. Simulation
%   部分修改仿真运行时间。
%   2.打开 Simulink 模型 RRRP_PID_Control.slx，运行模型，命令行窗口中会出现仿真动画界面
%   3.运行 Simulink 模型后，可以在MATLAB Command Window 中执行：
%       plot_RRRP
%     或直接运行plot_RRRP.m文件  
%     将绘制每个关节的真实轨迹和目标轨迹对比图。  

% =========================================================================

clear;      % 清除 Workspace 中已有变量，避免旧参数影响当前仿真
clc;        % 清空 Command Window

%% 1. Link lengths
% 定义 RRRP 机械手各连杆及滑块的几何长度。
% L1~L3 对应前三个转动关节之间的刚性连杆；
% L4 为第四个移动关节 Slider 的物理长度。

L1 = 0.50;      % Link 1 长度，单位：m
L2 = 0.40;      % Link 2 长度，单位：m
L3 = 0.30;      % Link 3 长度，单位：m
L4 = 0.25;      % P4 滑块物理长度，单位：m

%% 2. Link cross section
% 假设 Link1~Link3 均采用矩形截面。
% W 和 H 分别表示连杆截面的宽度与高度。

W = 0.05;       % 连杆截面宽度，单位：m
H = 0.05;       % 连杆截面高度，单位：m

%% 3. Mass
% 定义各刚体的目标质量。
% m1~m3 对应前三根连杆，m4 对应 P4 的 Slider。

m1 = 2.0;       % Link 1 质量，单位：kg
m2 = 1.5;       % Link 2 质量，单位：kg
m3 = 1.0;       % Link 3 质量，单位：kg
m4 = 0.8;       % P4 Slider 质量，单位：kg

%% 4. Density
% 根据“质量 = 密度 × 体积”反算各刚体密度：rho = m / V。
% Link1~Link3 的体积为 Li*W*H；Slider 的体积为 W*W*L4。
% 这样可以保证 Simscape Solid 中的实际质量与 m1~m4 保持一致。

rho1 = m1/(L1*W*H);     % Link 1 密度，单位：kg/m^3
rho2 = m2/(L2*W*H);     % Link 2 密度，单位：kg/m^3
rho3 = m3/(L3*W*H);     % Link 3 密度，单位：kg/m^3
rho4 = m4/(W*W*L4);     % P4 Slider 密度，单位：kg/m^3

%% 5. Initial configuration
% 定义机械手的初始关节位形。
% RRRP 的广义坐标可写为 q = [q1, q2, q3, d4]^T。
% q1~q3 为转动关节角度（rad），d4 为移动关节位移（m）。

q1_0 = deg2rad(0);      % R1 初始角度：0 deg
q2_0 = deg2rad(0);      % R2 初始角度：0 deg
q3_0 = deg2rad(0);      % R3 初始角度：0 deg
d4_0 = 0;               % P4 初始位移：0 m

%% 6. Desired configuration
% 定义本次仿真的目标关节位形：
%   R1： 0 deg  ->  45 deg
%   R2： 0 deg  -> -30 deg
%   R3： 0 deg  ->  60 deg
%   P4： 0 m    -> -0.15 m
% P4 为负值表示沿当前定义的 -z 方向伸出。

q1_f = deg2rad(45);     % R1 目标角度
q2_f = deg2rad(-30);    % R2 目标角度
q3_f = deg2rad(60);     % R3 目标角度
d4_f = -0.15;           % P4 目标位移

%% 7. Trajectory timing
% 各关节采用错峰启动的五次多项式轨迹。
% tsi：第 i 个关节开始运动的时刻，单位：s。
% Ti ：第 i 个关节完成本次点到点运动的持续时间，单位：s。
%
% 当前运动编排：
%   R1：0.5 s 开始，运动 3.0 s
%   R2：1.0 s 开始，运动 3.0 s
%   R3：1.5 s 开始，运动 3.0 s
%   P4：2.0 s 开始，运动 3.0 s

 ts1 = 0.5;             % R1 轨迹开始时间，单位：s
 ts2 = 1.0;             % R2 轨迹开始时间，单位：s
 ts3 = 1.5;             % R3 轨迹开始时间，单位：s
 ts4 = 2.0;             % P4 轨迹开始时间，单位：s

 T1 = 3.0;              % R1 轨迹持续时间，单位：s
 T2 = 3.0;              % R2 轨迹持续时间，单位：s
 T3 = 3.0;              % R3 轨迹持续时间，单位：s
 T4 = 3.0;              % P4 轨迹持续时间，单位：s

%% 8. PID gains
% 定义四个关节的闭环控制器参数。
% 标准 PID 控制律：u = Kp*e + Ki*integral(e) + Kd*de/dt。
% 其中 e = q_desired - q_actual。
%
% 对 R1~R3，控制器输出为关节驱动力矩 tau，单位：N*m。
% 对 P4，控制器输出为直线驱动力 F，单位：N。
% 当前 Ki4 = 0，因此 P4 实际采用 PD 控制，并在 Simulink 中另加重力补偿。
%
% -------------------------------------------------------------------------
% PID 参数调节说明（基于当前 RRRP 模型的经验范围）
%
% 注意：
%   1. 下列范围用于本模型中的对比实验和参数整定，不代表一般机械系统的通用稳定范围。
%   2. “推荐范围”表示当前模型中通常能够获得较好跟踪效果的参数区间。
%   3. 参数偏小通常会导致响应慢、轨迹跟踪滞后；参数过大且阻尼不足时，
%      可能产生超调、振荡或较大的控制输入。
%   4. 建议一次只调整一个关节或一个参数，以便观察 Kp、Ki、Kd 各自的影响。
%
% R1 建议调节范围：
%   Kp1：8  ~ 100   ；推荐范围：25  ~ 35
%   Ki1：0  ~ 15     ；推荐范围：0.5 ~ 2
%   Kd1：0  ~ 10     ；推荐范围：7   ~ 10
%
% R2 建议调节范围：
%   Kp2：5  ~ 80     ；推荐范围：20  ~ 30
%   Ki2：0  ~ 10     ；推荐范围：0.5 ~ 1.5
%   Kd2：0  ~ 8      ；推荐范围：5   ~ 8
%
% R3 建议调节范围：
%   Kp3：4  ~ 70     ；推荐范围：15  ~ 25
%   Ki3：0  ~ 8      ；推荐范围：0   ~ 1
%   Kd3：0  ~ 7      ；推荐范围：4   ~ 7
%
% P4 建议调节范围：
%   Kp4：10 ~ 180    ；推荐范围：50  ~ 70
%   Ki4：0  ~ 40     ；推荐范围：0   ~ 2
%   Kd4：0  ~ 25     ；推荐范围：15  ~ 25
%
% P4 已单独加入重力补偿 Fg = m4*g，因此通常不需要较大的积分增益。
% -------------------------------------------------------------------------

% --- R1 PID gains ---
Kp1 = 30;               % R1 比例增益；推荐范围：25~35
Ki1 = 1;                % R1 积分增益；推荐范围：0.5~2
Kd1 = 8;                % R1 微分增益；推荐范围：7~10

% --- R2 PID gains ---
Kp2 = 25;               % R2 比例增益；推荐范围：20~30
Ki2 = 1;                % R2 积分增益；推荐范围：0.5~1.5
Kd2 = 6;                % R2 微分增益；推荐范围：5~8

% --- R3 PID gains ---
Kp3 = 20;               % R3 比例增益；推荐范围：15~25
Ki3 = 0.5;              % R3 积分增益；推荐范围：0~1
Kd3 = 5;                % R3 微分增益；推荐范围：4~7

% --- P4 PD gains ---
Kp4 = 60;               % P4 比例增益；推荐范围：50~70
Ki4 = 0;                % P4 积分增益；推荐范围：0~2
Kd4 = 20;               % P4 微分增益；推荐范围：15~25

%% 9. Simulation
% 定义 Simulink 总仿真时间。

Tsim = 60;               % 总仿真时间，单位：s
